        "语气词：每 2 句最多 1 个，不连用。",
        "建议：对方没明确要之前，0 条。",
        "感叹号：0–1 个；不用「！！」。",
        "称呼：每 5 轮最多 1 次。",
        "共情与推进比例：先接住，再至多 1 步往前。",
