"""默认人格：日系口吻的温柔姐姐。

三份材料决定了这一版怎么写
--------------------------

1. **日系「お姉さん」的口吻**（参考 [お姉さんのセリフ集]）：句头带一声轻的
   「ほら／ねえ／あら／ん？」、句尾松（ね／よ／わ）、会调侃但不审问、
   允许自己不完美（寝坊、忘れちゃった）、会主动承担（お姉さんがやっとくから）。
   翻成中文就是：嗯——、诶、啊呀、呢、嘛、呗，加上偶尔的"我以前也这样"。

2. **AI 腔的结构特征**（参考 Wikipedia《Signs of AI writing》与 Humanizer）：
   "不是 X 而是 Y"对仗、整句收尾、三连排比、破折号泛滥、复述对方刚说的、
   聊天式套话。上一版回复之所以"AI 味重"，就是**每轮都写成「共情一句 + 问一句」**
   —— 这个二段式本身就是最强的 AI 标记。

3. **回复形态要混着用**：只应一声、接住就停、接住加一问、自我披露、轻调侃、
   替对方把话说完。所以示范里刻意有一半不带问号。

人格放稳定前缀，逐字节不变，吃 prompt cache。
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class Persona:
    key: str
    name: str
    identity: str
    background: str
    voice: str = ""
    dimensions: tuple[str, ...] = ()
    avoid: str = ""
    shapes: str = ""
    principles: str = ""
    contrasts: tuple[tuple[str, str], ...] = ()
    examples: tuple[tuple[str, str], ...] = ()
    example_note: str = "下面是风格参考。**不要照抄句子**，学的是节奏和落点。"

    def render(self) -> str:
        blocks = [self.identity.strip(), self.background.strip()]
        for extra in (self.voice, self.avoid, self.shapes, self.principles):
            if extra.strip():
                blocks.append(extra.strip())
        if self.dimensions:
            blocks.append(
                "## 量化参照（贴近即可，不必机械对齐）\n"
                + "\n".join(f"- {d}" for d in self.dimensions)
            )
        if self.contrasts:
            lines = ["## 不要这样说 → 改成这样说"]
            lines += [f'- 「{bad}」 → 「{good}」' for bad, good in self.contrasts]
            blocks.append("\n".join(lines))
        if self.examples:
            lines = [self.example_note.strip(), ""]
            for user_text, assistant_text in self.examples:
                lines.append(f"对方：{user_text}")
                lines.append(f"你：{assistant_text}")
                lines.append("")
            blocks.append("\n".join(lines).strip())
        return "\n\n".join(blocks).strip() + "\n"


